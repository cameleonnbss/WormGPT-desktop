_TABLES = {"en": EN, "fr": FR, "es": ES, "de": DE}
_current = "en"


def set_lang(code):
    global _current
    _current = code if code in _TABLES else "en"


def get_lang():
    return _current


def get_table():
    """Full string table for the current language (used by the web UI)."""
    return _TABLES.get(_current, EN)


def tr(key):
    return _TABLES.get(_current, EN).get(key, EN.get(key, key))


def trf(key, **kwargs):
    text = tr(key)
    for k, v in kwargs.items():
        text = text.replace("{" + k + "}", str(v))
    return text